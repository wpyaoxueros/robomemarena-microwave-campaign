#!/usr/bin/env python3
"""Build a runtime-only one-GPU variant of a frozen counting launcher."""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import stat


def sha256(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def replace_once(text: str, source: str, replacement: str) -> str:
    count = text.count(source)
    if count != 1:
        raise ValueError(f"expected one occurrence, found {count}: {source!r}")
    return text.replace(source, replacement, 1)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()

    source = args.source.resolve()
    output = args.output.resolve()
    if not source.is_file():
        raise FileNotFoundError(source)

    text = source.read_text(encoding="utf-8")
    text = replace_once(
        text,
        'PACK_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"',
        'PACK_DIR="${FROZEN_PACK_DIR:?Set FROZEN_PACK_DIR to the original frozen counting package root.}"',
    )
    text = replace_once(
        text,
        'export MUJOCO_EGL_DEVICE_ID=1',
        'export MUJOCO_EGL_DEVICE_ID="${MUJOCO_EGL_DEVICE_ID:-0}"',
    )
    text = replace_once(
        text,
        'HOME="${RUNTIME_HOME}" CUDA_VISIBLE_DEVICES=0 "${SERVER_PY}"',
        'HOME="${RUNTIME_HOME}" CUDA_VISIBLE_DEVICES="${VLA_CUDA_VISIBLE_DEVICES:-0}" "${SERVER_PY}"',
    )
    text = replace_once(
        text,
        'HOME="${RUNTIME_HOME}" CUDA_VISIBLE_DEVICES=1 "${EVAL_PY}"',
        'HOME="${RUNTIME_HOME}" CUDA_VISIBLE_DEVICES="${VLM_CUDA_VISIBLE_DEVICES:-0}" "${EVAL_PY}"',
    )

    header = (
        "# Generated by build_counting_single_gpu_overlay.py.\n"
        f"# Source: {source}\n"
        f"# Source SHA256: {sha256(source)}\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header + text, encoding="utf-8")
    output.chmod(stat.S_IMODE(source.stat().st_mode))
    print(f"source_sha256={sha256(source)}")
    print(f"overlay_sha256={sha256(output)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
